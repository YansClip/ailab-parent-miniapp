'use strict'
const test = require('node:test')
const assert = require('node:assert/strict')
const net = require('node:net')
const http = require('node:http')
const { setTimeout: delay } = require('node:timers/promises')
const { createReceiver } = require('../tools/mini-location-tcp/receiver')
const { createMonitor } = require('../tools/mini-location-tcp/monitor')
const { createMediaMonitor } = require('../tools/mini-location-tcp/media-monitor')
const { sendEvent } = require('../tools/mini-location-tcp/media-send')

async function setup(t, options = {}) {
  const receiver = createReceiver({ port: 0 })
  const address = await receiver.start()
  const monitor = createMonitor(receiver, { port: 0, tcpPort: address.port, getTunnel: () => ({ active: false, reason: 'test' }), ...options })
  const origin = await monitor.start()
  const html = await (await fetch(origin)).text()
  const token = /name="monitor-token" content="([a-f0-9]+)"/.exec(html)[1]
  t.after(async () => { await monitor.stop(); await receiver.stop() })
  const api = (route, body, headers = {}) => fetch(origin + route, { method: body === undefined ? 'GET' : 'POST', headers: { Origin: origin, 'x-monitor-token': token, 'Content-Type': 'application/json', ...headers }, body: body === undefined ? undefined : JSON.stringify(body) })
  return { receiver, address, origin, api }
}
test('monitor: local assets, no cache, CSP, token and cross-origin protection', async t => {
  const { origin, api } = await setup(t)
  const page = await fetch(origin)
  assert.equal(page.headers.get('cache-control'), 'no-store')
  assert.match(page.headers.get('content-security-policy'), /frame-ancestors 'none'/)
  assert.equal((await fetch(origin + '/app.js')).status, 200)
  assert.equal((await fetch(origin + '/style.css')).status, 200)
  assert.equal((await fetch(origin + '/api/state')).status, 403)
  assert.equal((await api('/api/state', undefined, { Origin: 'https://untrusted.example' })).status, 403)
  assert.equal((await api('/api/reveal', {})).status, 400)
  const status = await new Promise((resolve, reject) => {
    http.get(origin, { headers: { Host: 'untrusted.example' } }, res => { res.resume(); resolve(res.statusCode) }).on('error', reject)
  })
  assert.equal(status, 403)
})
test('monitor: coordinates private by default, future-only raw, CRLF counts, expiry erases', async t => {
  let now = Date.now()
  const { address, api } = await setup(t, { now: () => now })
  const socket = net.connect(address.port, address.host)
  t.after(() => socket.destroy())
  await new Promise(resolve => socket.once('connect', resolve))
  socket.write('120.0001_30.0001\r\n')
  await delay(35)
  let state = await (await api('/api/state')).json()
  assert.equal(state.stats.parsed, 1)
  assert.equal(JSON.stringify(state).includes('120.0001'), false)
  assert.equal(state.events.find(e => e.type === 'frame').lf, 1)
  assert.equal(state.events.find(e => e.type === 'frame').cr, 1)
  await api('/api/reveal', { confirmLocalOnly: true })
  state = await (await api('/api/state')).json()
  assert.ok(state.events.every(e => !e.raw))
  socket.write('120.0002_30.0002\r\n')
  await delay(35)
  state = await (await api('/api/state')).json()
  assert.ok(state.events.some(e => e.raw?.hex.endsWith('0D 0A')))
  now += 61000
  state = await (await api('/api/state')).json()
  assert.equal(JSON.stringify(state).includes('120.0002'), false)
  assert.equal(state.revealUntil, 0)
})
test('monitor: self-test explicitly identified and media adapter reaches local collector', async t => {
  const { origin, api } = await setup(t)
  assert.equal((await api('/api/test', { scene: 'normal' })).status, 200)
  const state = await (await api('/api/state')).json()
  assert.equal(state.stats.parsed, 1)
  assert.ok(state.events.some(e => e.type === 'self-test'))
  assert.equal((await sendEvent({ callId: 'test-call', mediaType: 'voice', source: 'client', seq: 1, state: 'calling' }, Number(new URL(origin).port))).accepted, true)
  assert.equal((await api('/api/media/event', { token: 'must-not-store' })).status, 400)
  assert.equal(JSON.stringify(await (await api('/api/state')).json()).includes('must-not-store'), false)
})
const event = overrides => ({ callId: 'test', mediaType: 'video', source: 'gateway', seq: 1, state: 'calling', ...overrides })
test('media monitor: validates schema, numbers and privacy-sensitive fields', () => {
  const monitor = createMediaMonitor()
  for (const input of [event({ token: 'secret' }), event({ metrics: { rttMs: -1 } }), event({ metrics: { packetLossPct: 101 } }), event({ seq: -1 }), event({ childAccepted: 'true' }), event({ metrics: { sdp: 'private' } }), event({ callId: '../../private' })]) assert.throws(() => monitor.ingest(input))
  assert.equal(monitor.snapshot().sessions.length, 0)
})
test('media monitor: client cannot confirm consent, stale/duplicate and ended sessions do not resurrect', () => {
  const monitor = createMediaMonitor()
  monitor.ingest(event({ source: 'client', state: 'connected', childAccepted: true, mediaReady: true, videoReady: true }))
  assert.equal(monitor.snapshot().sessions[0].confirmed, false)
  monitor.ingest(event({ state: 'connected', childAccepted: true, mediaReady: true, videoReady: true }))
  assert.equal(monitor.snapshot().sessions[0].confirmed, true)
  assert.equal(monitor.ingest(event({ state: 'connected' })).accepted, false)
  monitor.ingest(event({ seq: 2, state: 'ended' }))
  assert.equal(monitor.ingest(event({ seq: 3, state: 'connected' })).accepted, false)
  assert.equal(monitor.snapshot().sessions[0].state, 'ended')
  assert.equal(monitor.snapshot().connectedToHardware, false)
})
test('media monitor: bounded session retention, missing metrics not zero, simulated sessions isolated', () => {
  let now = 1000
  const monitor = createMediaMonitor(() => now)
  monitor.ingest(event({ callId: 'demo-1000' }))
  monitor.simulate('video', 'normal')
  assert.equal(monitor.snapshot().sessions.length, 2)
  assert.deepEqual(monitor.snapshot().sessions[0].metrics, {})
  assert.equal(monitor.snapshot().sessions.filter(s => s.simulated).length, 1)
  monitor.stopSimulation()
  assert.equal(monitor.snapshot().sessions.find(s => s.simulated).state, 'ended')
  now += 600001
  assert.equal(monitor.snapshot().sessions.length, 0)
  assert.equal(monitor.snapshot().events.length, 0)
  monitor.stop()
})
