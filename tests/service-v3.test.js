const test = require('node:test')
const assert = require('node:assert/strict')
const path = require('path')
const { createWxMock, fresh } = require('./helpers')
const storePath = path.resolve(__dirname, '../miniprogram/services/store.js')
const mockPath = path.resolve(__dirname, '../miniprogram/services/mock.js')
const apiPath = path.resolve(__dirname, '../miniprogram/services/api.js')
const curriculum = require('../miniprogram/services/curriculum')
function setup() {
  createWxMock()
  const store = fresh(storePath)
  store.init()
  store.setSession({ loggedIn: true, privacyAccepted: true, familyCreated: true, familyReady: true })
  let time = new Date('2026-09-12T12:00:00+08:00').getTime()
  const mock = fresh(mockPath)
  mock.__setClock(() => time)
  const api = fresh(apiPath)
  return { store, mock, api, advance(ms) { time += ms }, async finish(task, ms = 1800) { time += ms; return mock.getTask(task.id) }, getTime() { return time } }
}

test('V3: 正式目录31课，按年龄固定28+1门计划，六维只算coverage>0', async () => {
  const t = setup()
  assert.equal(curriculum.courses.length, 31)
  assert.equal(new Set(curriculum.courses.map((x) => x.id)).size, 31)
  let g = await t.api.getGrowth()
  assert.equal(g.plan.length, 29)
  assert.deepEqual(g.plan.filter((x) => x.id.startsWith('C')).map((x) => x.id), ['C01'])
  assert.deepEqual(g.dimensions.map((x) => x.key), ['system', 'data', 'control', 'ai', 'engineering', 'safety'])
  g.dimensions.forEach((d, i) => assert.equal(d.total, curriculum.planFor(11).filter((x) => x.coverage[i] > 0).length))
  assert.equal(g.ruleVersion, 'coverage-v1')
  assert.equal(g.curriculumVersion, 'V3.1')
  assert.equal(g.plan[0].webLevelId, 'demo-level-B01')
  t.store.setCurrentChildId('child-xinghe')
  g = await t.api.getGrowth()
  assert.deepEqual(g.plan.filter((x) => x.id.startsWith('C')).map((x) => x.id), ['C02'])
})

